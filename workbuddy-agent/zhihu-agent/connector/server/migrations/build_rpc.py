"""Build the fixed SQL allowlist for the private classroom HTTPS transaction RPC."""
import ast
import hashlib
import json
from pathlib import Path

SERVER = Path(__file__).resolve().parents[1]


def parts(sql):
    values, buf, quoted, pos = [], '', False, 0
    while pos < len(sql):
        char = sql[pos]
        if char == "'":
            if quoted and pos + 1 < len(sql) and sql[pos + 1] == "'":
                buf += "''"
                pos += 2
                continue
            quoted = not quoted
        if char == '?' and not quoted:
            values.append(buf)
            buf = ''
        else:
            buf += char
        pos += 1
    values.append(buf)
    return values


def literal(value):
    return "'" + value.replace("'", "''") + "'"


def build():
    sqls = set()
    for name in ('classroom.py', 'classroom_postgres.py'):
        tree = ast.parse((SERVER / 'zhihu_mcp' / name).read_text(encoding='utf-8'))
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and isinstance(node.func.value, ast.Name) and node.func.value.id in ('db', 'self')
                    and node.func.attr == 'execute' and node.args
                    and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)):
                continue
            sql = node.args[0].value
            if sql.split()[0].upper() in {'SELECT', 'INSERT', 'UPDATE', 'DELETE'}:
                assert ';' not in sql
                sqls.add(sql)
    preamble = '''-- Generated by build_rpc.py. Only the backend service role can invoke this RPC.
BEGIN;
SELECT pg_advisory_xact_lock(734218603119);
CREATE TABLE IF NOT EXISTS zhihu_classroom.tx_revision(id INTEGER PRIMARY KEY CHECK(id=1), revision BIGINT NOT NULL);
INSERT INTO zhihu_classroom.tx_revision VALUES(1,0) ON CONFLICT(id) DO NOTHING;
CREATE TABLE IF NOT EXISTS zhihu_classroom.sql_registry(key TEXT PRIMARY KEY, parts JSONB NOT NULL, read_only BOOLEAN NOT NULL);
REVOKE ALL ON zhihu_classroom.tx_revision, zhihu_classroom.sql_registry FROM PUBLIC;
'''
    entries = []
    for sql in sorted(sqls):
        key = hashlib.sha256(sql.encode()).hexdigest()
        entries.append('INSERT INTO zhihu_classroom.sql_registry VALUES(' + literal(key) + ','
                       + literal(json.dumps(parts(sql), ensure_ascii=False)) + '::jsonb,'
                       + ('true' if sql.startswith('SELECT ') else 'false')
                       + ') ON CONFLICT(key) DO UPDATE SET parts=excluded.parts,read_only=excluded.read_only;')
    functions = '''
CREATE OR REPLACE FUNCTION zhihu_classroom.run_statement(command JSONB) RETURNS JSONB
LANGUAGE plpgsql SET search_path = pg_catalog, zhihu_classroom AS $fn$
DECLARE entry zhihu_classroom.sql_registry%ROWTYPE; stmt TEXT; i INTEGER; rows JSONB; affected BIGINT;
BEGIN
    SELECT * INTO STRICT entry FROM zhihu_classroom.sql_registry WHERE key=command->>'key';
    IF jsonb_typeof(command->'params') IS DISTINCT FROM 'array'
       OR jsonb_array_length(command->'params') <> jsonb_array_length(entry.parts)-1 THEN
        RAISE EXCEPTION 'Invalid parameter list';
    END IF;
    stmt := entry.parts->>0;
    IF jsonb_array_length(entry.parts)>1 THEN
        FOR i IN 0..jsonb_array_length(entry.parts)-2 LOOP
            -- Values are quoted once and appended, never subject to later replacements.
            stmt := stmt || quote_nullable(command->'params'->>i) || (entry.parts->>(i+1));
        END LOOP;
    END IF;
    IF entry.read_only THEN
        EXECUTE 'SELECT coalesce(jsonb_agg(to_jsonb(q)), ''[]''::jsonb) FROM (' || stmt || ') q' INTO rows;
        affected := jsonb_array_length(rows);
    ELSE
        EXECUTE stmt;
        GET DIAGNOSTICS affected = ROW_COUNT;
        rows := '[]'::jsonb;
    END IF;
    RETURN jsonb_build_object('rows',rows,'rowcount',affected);
END;
$fn$;
REVOKE ALL ON FUNCTION zhihu_classroom.run_statement(JSONB) FROM PUBLIC;

CREATE OR REPLACE FUNCTION public.zhihu_classroom_tx(
    p_mode TEXT, p_revision BIGINT, p_writes JSONB, p_query JSONB
) RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, zhihu_classroom AS $fn$
DECLARE current_revision BIGINT; command JSONB; result JSONB := '{"rows":[],"rowcount":0}'::jsonb;
BEGIN
    IF p_mode NOT IN ('query','commit') OR p_mode IS NULL
       OR jsonb_typeof(p_writes) IS DISTINCT FROM 'array'
       OR jsonb_array_length(p_writes)>1200 THEN
        RETURN jsonb_build_object('error','invalid_transaction');
    END IF;
    IF (SELECT version FROM zhihu_classroom.schema_version WHERE id=1) IS DISTINCT FROM 1 THEN
        RETURN jsonb_build_object('error','schema_version');
    END IF;
    SELECT revision INTO STRICT current_revision FROM zhihu_classroom.tx_revision WHERE id=1 FOR UPDATE;
    IF p_revision IS NOT NULL AND p_revision <> current_revision THEN
        RETURN jsonb_build_object('error','conflict');
    END IF;
    IF p_mode='query' THEN
        BEGIN
            FOR command IN SELECT value FROM jsonb_array_elements(p_writes) LOOP
                PERFORM zhihu_classroom.run_statement(command);
            END LOOP;
            result := zhihu_classroom.run_statement(p_query);
            -- Roll back all preview writes while retaining the local result variable.
            RAISE EXCEPTION USING ERRCODE='ZX001',MESSAGE='rollback preview';
        EXCEPTION WHEN SQLSTATE 'ZX001' THEN NULL;
        END;
    ELSE
        FOR command IN SELECT value FROM jsonb_array_elements(p_writes) LOOP
            PERFORM zhihu_classroom.run_statement(command);
        END LOOP;
        UPDATE zhihu_classroom.tx_revision SET revision=revision+1 WHERE id=1 RETURNING revision INTO current_revision;
    END IF;
    RETURN jsonb_build_object('revision',current_revision,'result',result);
EXCEPTION WHEN integrity_constraint_violation THEN
    RETURN jsonb_build_object('error','duplicate');
WHEN OTHERS THEN
    -- Never return SQL, parameter values or authentication data.
    RETURN jsonb_build_object('error','storage_operation_failed');
END;
$fn$;
REVOKE ALL ON FUNCTION public.zhihu_classroom_tx(TEXT,BIGINT,JSONB,JSONB) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.zhihu_classroom_tx(TEXT,BIGINT,JSONB,JSONB) FROM anon,authenticated;
GRANT EXECUTE ON FUNCTION public.zhihu_classroom_tx(TEXT,BIGINT,JSONB,JSONB) TO service_role;
COMMIT;
NOTIFY pgrst, 'reload schema';
'''
    return preamble + '\n'.join(entries) + '\n' + functions


if __name__ == '__main__':
    path = Path(__file__).with_name('002_classroom_rpc.sql')
    path.write_text(build(), encoding='utf-8')
    print(path)
